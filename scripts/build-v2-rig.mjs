// Reads reference/character/sehaz-v2.svg (the Figma v2 export) and writes src/art/character/v2shapes.ts:
// clean path data per part, with no <use>/<mask> and no colliding ids, ready to be rigged in Character.tsx.
import fs from 'node:fs';
const svg = fs.readFileSync('reference/character/sehaz-v2.svg', 'utf8');
const def = (n) => svg.match(new RegExp(`id="stroke${n}_0_4" d="([^"]*)"`))[1];
const byId = (id) => svg.match(new RegExp(`<path id="${id}" d="([^"]*)"`))[1];
const out = {
  // trousers and skirt: one shape, split into two legs by the rig
  skirt: def(24),
  // legs: [shin, shoeBlue, shoeGrey, sole, tabA, tabB]
  legR: { shin: def(6), shoe: def(0), grey: def(2), sole: def(4), tabA: def(8), tabB: def(10) },
  legL: { shin: def(18), shoe: def(12), grey: def(14), sole: def(16), tabA: def(20), tabB: def(22) },
  hair: def(27), shirt: def(29), belt: def(31), jacketR: def(33), jacketL: def(35), face: def(37), bag: def(39),
  earHole: byId('ear hole'), blush: byId('blush'), blush2: byId('blush_2'), pocket: byId('pocket'),
  seamR: byId('hand_2'), seamL: byId('sleeve_3'), bagHandle: byId('bag_2'),
};
const body = Object.entries(out).map(([k, v]) => `export const ${k.toUpperCase()} = ${JSON.stringify(v, null, 2)} as const;`).join('\n');
fs.writeFileSync('src/art/character/v2shapes.ts', `// GENERATED by scripts/build-v2-rig.mjs from reference/character/sehaz-v2.svg. Do not edit by hand.\n${body}\n`);
console.log('ok');
