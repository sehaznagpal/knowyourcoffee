// Vectorises only the hair of reference/character/style-bun-closeup.png with potrace and writes the paths, untouched, to
// src/art/character/hair.ts. Run: node scripts/trace-hair.mjs
import { createRequire } from 'node:module';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const require = createRequire(import.meta.url);
const potrace = require('potrace');
const root = fileURLToPath(new URL('../', import.meta.url));
const src = PNG.sync.read(readFileSync(join(root, 'reference/character/style-bun-closeup.png')));
const { width: W, height: H, data } = src;

const dark = new Uint8Array(W * H);
for (let i = 0; i < W * H; i++) dark[i] = (data[i * 4] + data[i * 4 + 1] + data[i * 4 + 2]) / 3 < 100 ? 1 : 0;

// the big connected black component holds hair, face outline and wisps together
const label = new Int32Array(W * H);
const comps = [];
for (let i = 0; i < W * H; i++) {
  if (!dark[i] || label[i]) continue;
  const id = comps.length + 1, stack = [i];
  let area = 0;
  label[i] = id;
  while (stack.length) {
    const p = stack.pop();
    area++;
    const x = p % W;
    for (const q of [p - 1, p + 1, p - W, p + W]) {
      if (q < 0 || q >= W * H || !dark[q] || label[q] || Math.abs((q % W) - x) > 1) continue;
      label[q] = id;
      stack.push(q);
    }
  }
  comps.push({ id, area });
}
const big = comps.reduce((a, b) => (b.area > a.area ? b : a)).id;

// Pieces, in reference pixels. Neighbouring pieces overlap by ~10 px so the cuts hide inside solid black.
// The face outline (left x 152-171, right x <= 306 below y 232) is left out.
const pieces = {
  bun: (x, y) => y <= 134,
  cap: (x, y) => y >= 124 && (y <= 248 ? y <= 232 || x <= 146 || x >= 309 : false),
  wispsLeft: (x, y) => y >= 240 && y <= 285 && x <= 146,
  wispsRight: (x, y) => y >= 240 && y <= 285 && x >= 309,
};

const dir = mkdtempSync(join(tmpdir(), 'hair-'));
const out = {};
for (const [name, keep] of Object.entries(pieces)) {
  const png = new PNG({ width: W, height: H });
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const on = label[y * W + x] === big && keep(x, y);
    const k = (y * W + x) * 4;
    png.data[k] = png.data[k + 1] = png.data[k + 2] = on ? 0 : 255;
    png.data[k + 3] = 255;
  }
  const file = join(dir, name + '.png');
  writeFileSync(file, PNG.sync.write(png));
  out[name] = await new Promise((res, rej) => potrace.trace(file, { turdSize: 2 }, (e, svg) => (e ? rej(e) : res(svg))));
  out[name] = [...out[name].matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
  console.log(name, out[name].length, 'chars of path');
}

const ts = `// Generated by scripts/trace-hair.mjs (potrace on reference/character/style-bun-closeup.png). Do not edit by hand.
// Coordinates are reference pixels (${W} x ${H}); Character places them with HAIR_FIT.
export const HAIR = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, 'src/art/character/hair.ts'), ts);
